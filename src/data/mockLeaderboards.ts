/** Deterministic soft color from a display name (avatar background). */
export function leaderboardAvatarTone(name: string): { bg: string; fg: string } {
  let hash = 0;
  for (let i = 0; i < name.length; i++) hash = (hash * 31 + name.charCodeAt(i)) >>> 0;
  const hues = [210, 165, 280, 145, 25, 340, 195, 255];
  const hue = hues[hash % hues.length];
  return {
    bg: `hsl(${hue} 42% 88%)`,
    fg: `hsl(${hue} 40% 28%)`,
  };
}

export function leaderboardInitials(name: string): string {
  const parts = name.trim().split(/\s+/).filter(Boolean);
  if (parts.length === 0) return "?";
  if (parts.length === 1) return parts[0].slice(0, 2).toUpperCase();
  return `${parts[0][0] ?? ""}${parts[1][0] ?? ""}`.toUpperCase();
}

